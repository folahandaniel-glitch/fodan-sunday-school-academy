// Regenerates src/content/registry.ts from the curriculum files that exist. Run: node scripts/gen-registry.mjs
import fs from "node:fs";
const dir = "src/content/curricula";
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^c\d{2}\.ts$/.test(f)).sort() : [];
const imports = files.map((f) => `import { lessons as c${f.slice(1, 3)} } from "./curricula/${f.replace(".ts", "")}";`);
const entries = files.map((f) => `  ${Number(f.slice(1, 3))}: c${f.slice(1, 3)},`);
fs.writeFileSync("src/content/registry.ts", `// GENERATED by scripts/gen-registry.mjs from src/content/curricula/c*.ts. Do not edit by hand.
import type { LessonSeed } from "./types";
${imports.join("\n")}

export const CONTENT: Record<number, LessonSeed[]> = {
${entries.join("\n")}
};
`);
console.log(`registry: ${files.length} curriculum file(s)`);
