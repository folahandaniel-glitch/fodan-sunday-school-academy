// Builds src/lib/ui-text-catalog.ts: every piece of interface wording an administrator can replace under
// Admin > Website content > Interface wording. The wording written in the code is the default and the lookup key.
// Run: node scripts/gen-ui-catalog.mjs   (also runs as part of `npm run registry` and the Vercel build)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(root, "src");

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else if (/\.tsx?$/.test(e.name) && !/ui-text-catalog\.ts$/.test(e.name)) out.push(p);
  }
  return out;
}
const groupOf = (rel) => {
  if (rel.includes("(site)/layout") || rel.includes("mobile-nav")) return "Public header and footer";
  if (rel.includes("(auth)")) return "Sign in, registration and password screens";
  if (rel.includes("lib/nav")) return "Portal menus";
  if (rel.includes("app-shell") || rel.includes("member-shell") || rel.includes("components/ui")) return "Portal frame and shared elements";
  if (rel.includes("app/admin")) return "Admin pages";
  if (rel.includes("app/church")) return "Church portal pages";
  if (rel.includes("app/learn")) return "Learner portal pages";
  if (rel.includes("app/teach")) return "Teacher portal pages";
  if (rel.includes("app/forum")) return "Forum pages";
  if (rel.includes("app/app")) return "Member pages";
  if (rel.includes("(site)")) return "Public pages";
  return "Other screens and components";
};
const DQ = String.raw`"((?:[^"\\\n]|\\.)*)"`;
const unq = (s) => { try { return JSON.parse(`"${s}"`); } catch { return s; } };

export function buildCatalog() {
  const found = new Map(); // text -> group
  const add = (text, group) => { text = unq(text); if (text.trim() && !found.has(text)) found.set(text, group); };
  for (const f of walk(SRC).sort()) {
    const rel = path.relative(SRC, f).replaceAll("\\", "/");
    const group = groupOf(rel);
    const src = fs.readFileSync(f, "utf8");
    for (const m of src.matchAll(new RegExp(String.raw`(?<![\w.$])t\(\s*${DQ}`, "g"))) add(m[1], group);
    for (const line of src.split("\n")) {
      if (/<PageHeader\b/.test(line)) {
        for (const m of line.matchAll(new RegExp(String.raw`\b(?:title|sub)=${DQ}`, "g"))) add(m[1], group);
        for (const m of line.matchAll(new RegExp(String.raw`\{ label: ${DQ}`, "g"))) add(m[1], group);
      }
      if (/<Empty\b/.test(line)) for (const m of line.matchAll(new RegExp(String.raw`\btitle=${DQ}`, "g"))) add(m[1], group);
      if (/<Empty\b/.test(line)) for (const m of line.matchAll(new RegExp(String.raw`>([A-Z][^<>{}"]{8,})</Empty>`, "g"))) add(m[1], group);
      if (/<AppShell\b/.test(line) || rel.includes("member-shell")) for (const m of line.matchAll(new RegExp(String.raw`area=${DQ}`, "g"))) add(m[1], group);
      if (rel.includes("member-shell")) for (const m of line.matchAll(new RegExp(String.raw`\? ${DQ}|: ${DQ}`, "g"))) add(m[1] ?? m[2], group);
    }
    if (rel === "lib/nav.ts") for (const m of src.matchAll(new RegExp(String.raw`\b(?:label|group): ${DQ}`, "g"))) add(m[1], group);
  }
  // Public site defaults edited elsewhere (navigation, footer) are translated too, so offer them here.
  const settings = fs.readFileSync(path.join(SRC, "server/settings.ts"), "utf8");
  const navBlock = settings.match(/nav: \[([\s\S]*?)\] as/)?.[1] ?? "";
  for (const m of navBlock.matchAll(new RegExp(String.raw`label: ${DQ}`, "g"))) add(m[1], "Public header and footer");
  const foot = settings.match(/footer: \{([\s\S]*?)\n  \},/)?.[1] ?? "";
  for (const m of foot.matchAll(new RegExp(String.raw`(?:about|label|copyright): ${DQ}`, "g"))) add(m[1], "Public header and footer");
  const groups = new Map();
  for (const [text, g] of found) { if (!groups.has(g)) groups.set(g, []); groups.get(g).push(text); }
  const order = ["Public header and footer", "Sign in, registration and password screens", "Portal frame and shared elements", "Portal menus", "Public pages", "Admin pages", "Church portal pages", "Learner portal pages", "Teacher portal pages", "Forum pages", "Member pages", "Other screens and components"];
  return order.filter((g) => groups.has(g)).map((g) => ({ group: g, items: groups.get(g) }));
}

export function render(catalog) {
  return `// GENERATED by scripts/gen-ui-catalog.mjs. Do not edit by hand.
// Every interface text an administrator can replace under Admin > Website content > Interface wording.
export const UI_TEXT_CATALOG: { group: string; items: string[] }[] = ${JSON.stringify(catalog, null, 2)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const c = buildCatalog();
  fs.writeFileSync(path.join(SRC, "lib/ui-text-catalog.ts"), render(c));
  console.log(`ui-text catalog: ${c.reduce((n, g) => n + g.items.length, 0)} texts in ${c.length} groups`);
}
